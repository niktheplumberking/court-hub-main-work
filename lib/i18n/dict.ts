// Arabic rules honored (senior-arabic-rtl-dev):
//  - counts go through Intl.PluralRules (all six Arabic categories),
//  - Arabic punctuation (، ؟) in Arabic strings, no letter-spaced Arabic,
//  - Western digits (UAE digital-product default),
//  - brand/proper nouns stay Latin.
// ============================================================================

/** Count formatter with full Arabic plural categories. */
export function plural(
  locale: Locale,
  n: number,
  forms: { zero?: string; one: string; two?: string; few?: string; many?: string; other: string }
): string {
  const cat = new Intl.PluralRules(locale === 'ar' ? 'ar' : 'en').select(n) as keyof typeof forms;
  const raw = forms[cat] ?? forms.other;
  return raw.replace('#', String(n));
}

